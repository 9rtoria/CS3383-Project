let currentLocale: Locale = "en";
let hydrated = false;
const listeners = new Set<() => void>();

function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "zh-TW";
}

function hydrateLocale() {
  if (hydrated || typeof window === "undefined") return;
  hydrated = true;
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (isLocale(stored)) currentLocale = stored;
    else if (document.documentElement.lang === "zh-TW") currentLocale = "zh-TW";
  } catch {
    // private windows can refuse storage.
  }
}

export function getLocale(): Locale {
  hydrateLocale();
  return currentLocale;
}

export function setLocale(locale: Locale): void {
  hydrateLocale();
  if (currentLocale === locale) return;
  currentLocale = locale;
  if (typeof document !== "undefined") {
    document.documentElement.lang = locale;
    document.documentElement.dataset.locale = locale;
    try {
      localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    } catch {
      // Storage is optional.
    }
  }
  listeners.forEach((listener) => listener());
}

export function subscribeLocale(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function translate(key: string, vars?: Vars): string {
  const template = getLocale() === "zh-TW" ? zhTW[key] ?? key : key;
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(vars[name] ?? `{{${name}}}`));
}

export function useI18n() {
  const locale = useSyncExternalStore(subscribeLocale, getLocale, () => "en" as Locale);
  return {
    locale,
    setLocale,
    t: (key: string, vars?: Vars) => {
      const template = locale === "zh-TW" ? zhTW[key] ?? key : key;
      if (!vars) return template;
      return template.replace(/\{\{(\w+)\}\}/g, (_, name: string) => String(vars[name] ?? `{{${name}}}`));
    },
  };
}

export function translatedKeys(): string[] {
  return Object.keys(zhTW);
}

export function translateReason(reason: string, t: (key: string) => string): string {
  const overdue = reason.match(/^Overdue since (.+)$/);
  if (overdue) return `${t("Overdue since")} ${overdue[1]}`;
  const priority = reason.match(/^(Urgent|High) priority with no due date$/);
  if (priority) return `${t(priority[1]!)} ${t("priority with no due date")}`;
  return t(reason);
}
