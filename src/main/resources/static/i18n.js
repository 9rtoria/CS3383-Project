  let currentLocale = "en";
  const listeners = new Set();

  function isLocale(value) {
    return value === "en" || value === "zh-TW";
  }

  function readStoredLocale() {
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY);
      if (isLocale(stored)) return stored;
    } catch { /* storage is optional */ }
    return document.documentElement.lang === "zh-TW" ? "zh-TW" : "en";
  }

  function t(key, vars) {
    const template = currentLocale === "zh-TW" ? (zhTW[key] ?? key) : key;
    if (!vars) return template;
    return template.replace(/\{\{(\w+)\}\}/g, (_, name) => String(vars[name] ?? `{{${name}}}`));
  }

  const textOriginals = new WeakMap();
  const attributeOriginals = new WeakMap();

  function translateCore(value) {
    if (!value || currentLocale !== "zh-TW") return value;
    const leading = value.match(/^\s*/)?.[0] ?? "";
    const trailing = value.match(/\s*$/)?.[0] ?? "";
    const core = value.trim();
    if (!core) return value;
    return `${leading}${zhTW[core] ?? core}${trailing}`;
  }

  function translateSubtree(root) {
    if (!root) return;
    const skip = (node) => {
      const element = node.nodeType === Node.ELEMENT_NODE ? node : node.parentElement;
      return element && (element.closest?.("[data-i18n-skip]") || element.closest?.("script, style, textarea"));
    };
    const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) textNodes.push(walker.currentNode);
    for (const node of textNodes) {
      if (skip(node)) continue;
      if (!textOriginals.has(node)) textOriginals.set(node, node.nodeValue);
      const original = textOriginals.get(node);
      const translated = currentLocale === "zh-TW" ? translateCore(original) : original;
      if (translated !== node.nodeValue) node.nodeValue = translated;
    }
    for (const element of root.querySelectorAll("[placeholder], [aria-label], [title]")) {
      if (element.closest?.("[data-i18n-skip]")) continue;
      let originals = attributeOriginals.get(element);
      if (!originals) {
        originals = {};
        attributeOriginals.set(element, originals);
      }
      for (const attribute of ["placeholder", "aria-label", "title"]) {
        const value = element.getAttribute(attribute);
        if (!value) continue;
        if (!(attribute in originals)) originals[attribute] = value;
        const original = originals[attribute];
        const translated = currentLocale === "zh-TW" ? translateCore(original) : original;
        if (translated !== value) element.setAttribute(attribute, translated);
      }
    }
  }

  function setLocale(locale) {
    if (!isLocale(locale) || currentLocale === locale) return currentLocale;
    currentLocale = locale;
    document.documentElement.lang = locale;
    document.documentElement.dataset.locale = locale;
    try { window.localStorage.setItem(STORAGE_KEY, locale); } catch { /* ignore */ }
    translateSubtree(document.body);
    listeners.forEach((listener) => listener(locale));
    window.dispatchEvent(new CustomEvent(CHANGE_EVENT, { detail: locale }));
    return currentLocale;
  }

  function getLocale() {
    return currentLocale;
  }

  function subscribe(listener) {
    listeners.add(listener);
    return () => listeners.delete(listener);
  }

  function translateReason(reason, translate = t) {
    const overdue = String(reason).match(/^Overdue since (.+)$/);
    if (overdue) return `${translate("Overdue since")} ${overdue[1]}`;
    const priority = String(reason).match(/^(Urgent|High) priority with no due date$/);
    if (priority) return `${translate(priority[1])} ${translate("priority with no due date")}`;
    return translate(reason);
  }

  window.DriftI18n = { getLocale, setLocale, subscribe, t, translateSubtree, translateReason, dictionary: zhTW };

